"""Rendering skill: Markdown / JSON / DOT output for artefacts."""

from __future__ import annotations

import json
from typing import Any, Dict, List


def render_markdown_doc(doc: dict) -> str:
    out: List[str] = []
    out.append(f"# {doc.get('title', 'Legacy System Documentation')}")
    out.append("")
    out.append(f"_Generated by AURA Documentation Generator · provider: {doc.get('provider', '?')} · "
               f"rules: {doc.get('rule_count', 0)} · confidence states: "
               f"{json.dumps(doc.get('confidence_distribution', {}))}_")
    out.append("")
    for section in doc.get("sections", []):
        level = min(6, 2 + section.get("depth", 0))
        out.append("#" * level + " " + section.get("title", "Section"))
        out.append("")
        if section.get("summary"):
            out.append(section["summary"])
            out.append("")
        for block in section.get("blocks", []):
            out.append(render_block(block))
            out.append("")
    if doc.get("audit"):
        out.append("---")
        out.append("")
        out.append("## Audit Trail")
        out.append("")
        audit = doc["audit"]
        out.append(f"- source references: {audit.get('total_references', 0)} "
                   f"(valid spans: {audit.get('valid_references', 0)}, "
                   f"rate: {audit.get('valid_span_rate', 0):.2%})")
        for ref in audit.get("references", [])[:40]:
            mark = "OK" if ref.get("valid") else "INVALID"
            out.append(f"- [{mark}] {ref.get('file')}:{ref.get('line_start')}-{ref.get('line_end')} "
                       f"({ref.get('artefact', '?')})")
    out.append("")
    return "\n".join(out)


def render_block(block: dict) -> str:
    kind = block.get("kind", "text")
    if kind == "rules":
        out = []
        for r in block.get("items", []):
            out.append(f"- **{r.get('id', '?')}** [{r.get('confidence_state', 'inferred')}] "
                       f"{r.get('statement', '')}  \n  _source: {r.get('source', {}).get('file', '?')}:"
                       f"{r.get('source', {}).get('line_start', '?')}-"
                       f"{r.get('source', {}).get('line_end', '?')} · "
                       f"dynamic: {r.get('dynamic_label') or 'n/a'}_")
        return "\n".join(out) if out else "_none_"
    if kind == "code":
        lang = block.get("language", "")
        return f"```{lang}\n{block.get('text', '')}\n```"
    if kind == "table":
        rows = block.get("rows", [])
        if not rows:
            return "_empty table_"
        head = rows[0]
        lines = ["| " + " | ".join(str(c) for c in head) + " |",
                 "|" + "|".join(" --- " for _ in head) + "|"]
        for row in rows[1:]:
            lines.append("| " + " | ".join(str(c) for c in row) + " |")
        return "\n".join(lines)
    return block.get("text", "")


def render_bsg_dot(bsg: dict) -> str:
    lines = ["digraph BSG {", "  rankdir=LR;", '  node [shape=box, fontname="Helvetica"];']
    for n in bsg.get("nodes", []):
        color = {
            "confirmed_both": "#2e7d32", "confirmed_static": "#66bb6a",
            "confirmed_dynamic": "#42a5f5", "inferred": "#ffca28",
            "contradicted": "#e53935", "gap": "#9e9e9e",
        }.get(n.get("confidence_state", "inferred"), "#cccccc")
        style = ", style=filled, fillcolor=\"%s\"" % color
        if n.get("blocked"):
            style += ", peripheries=2"
        lines.append(f'  "{n.get("id")}" [label="{n.get("id")}: {n.get("operation", "")[:40]}"{style}];')
    for e in bsg.get("edges", []):
        lines.append(f'  "{e.get("from")}" -> "{e.get("to")}" [label="{e.get("label", "sequence")}"];')
    lines.append("}")
    return "\n".join(lines)


def to_json(obj: Any) -> str:
    return json.dumps(obj, indent=2, default=str)
